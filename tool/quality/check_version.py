"""Validate application release metadata and scenery fixture integrity."""
import json
from pathlib import Path
import re
import zipfile
import zlib

ROOT = Path(__file__).resolve().parents[2]
VERSION = r'(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)'
PUBSPEC_PATTERN = re.compile(r'^version:[ \t]*(' + VERSION + r')\+([1-9]\d*)[ \t]*$', re.M)
GENERATED = 'lib/core/models/application_version.dart'
FIXTURE = 'test/fixtures/scenery/conversion_open_wall.fpvscenery'
README_PATTERN = re.compile(r'^(\*\*Current source version:\*\* `)[^`]+(`[^\n]*)$', re.M)


def read_version(text):
    matches = PUBSPEC_PATTERN.findall(text)
    if len(matches) != 1:
        raise ValueError('pubspec.yaml: expected one major.minor.patch+build entry')
    return matches[0][0], int(matches[0][1])


def generated_version(version, build):
    return ('// Generated by tool/maintenance/bump_version.py. Do not edit.\n'
             f"const applicationVersion = '{version}';\n"
             f'const applicationBuildNumber = {build};\n')


def fixture_errors(root, version):
    try:
        with zipfile.ZipFile(root / FIXTURE) as archive:
            bad = archive.testzip()
            if bad is not None:
                raise ValueError(f'CRC failure: {bad}')
            manifest = json.loads(archive.read('manifest.json'))
            minimum = manifest['scenery']['minimumAppVersion']
            if not isinstance(minimum, str) or not re.fullmatch(VERSION, minimum):
                raise ValueError('invalid minimumAppVersion')
            if tuple(map(int, minimum.split('.'))) > tuple(map(int, version.split('.'))):
                raise ValueError(f'fixture requires newer application {minimum}')
    except (OSError, zipfile.BadZipFile, ValueError, KeyError, TypeError, RuntimeError, NotImplementedError, zlib.error) as exc:
        return [f'{FIXTURE}: {exc}. Restore the original binary fixture; do not edit ZIP bytes as text.']
    return []


def check(root=ROOT):
    root = Path(root)
    try:
        version, build = read_version((root / 'pubspec.yaml').read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        return [str(exc)]
    errors = []
    try:
        if (root / GENERATED).read_text(encoding='utf-8') != generated_version(version, build):
            errors.append(f'{GENERATED}: stale; run python tool/maintenance/bump_version.py --sync')
    except OSError:
        errors.append(f'{GENERATED}: missing; run python tool/maintenance/bump_version.py --sync')
    errors.extend(fixture_errors(root, version))
    readme = (root / 'README.md').read_text(encoding='utf-8')
    if len(README_PATTERN.findall(readme)) != 1 or not re.search(
            r'^\*\*Current source version:\*\* `' + re.escape(f'{version}+{build}') + r'`', readme, re.M):
        errors.append('README.md: current source version mismatch')
    if not re.search(r'^## \[' + re.escape(version) + r'\]', (root / 'CHANGELOG.md').read_text(encoding='utf-8'), re.M):
        errors.append('CHANGELOG.md: missing version entry')
    return errors


if __name__ == '__main__':
    errors = check()
    if errors:
        raise SystemExit('\n'.join(errors))
    print('Application version, generated metadata, release docs and scenery fixture integrity agree.')
