import 'package:flutter/widgets.dart';

import 'generated/fpv_strings.dart';
import 'generated/fpv_strings_de.dart';
import 'generated/fpv_strings_en.dart';
import 'legacy_message_lookup.g.dart';

/// The persistent language selection remains stable across localization migrations.
enum AppLanguage {
  german('de', 'Deutsch'),
  english('en', 'English');

  const AppLanguage(this.code, this.nameInLanguage);

  final String code;
  final String nameInLanguage;

  Locale get locale => Locale(code);

  static AppLanguage fromCode(String? code) =>
      code == english.code ? english : german;
}

/// Compatibility facade for older widgets and tests.
/// New UI should use [FpvStrings] through the [AppLocalizedContext] extension.
class AppLocalizations {
  const AppLocalizations(this.language);

  final AppLanguage language;

  static const delegate = FpvStrings.delegate;
  static const supportedLocales = FpvStrings.supportedLocales;

  static AppLocalizations? maybeOf(BuildContext context) {
    final strings = Localizations.of<FpvStrings>(context, FpvStrings);
    return strings == null
        ? null
        : AppLocalizations(AppLanguage.fromCode(strings.localeName));
  }

  /// Retained for tests and non-widget code; the catalog is generated by Flutter.
  static String message(
    AppLanguage? language,
    String source,
    List<Object?> arguments,
  ) {
    if (language == null) return interpolateSource(source, arguments);
    final strings = switch (language) {
      AppLanguage.german => FpvStringsDe(),
      AppLanguage.english => FpvStringsEn(),
    };
    return lookupLocalizedMessage(strings, source, arguments);
  }
}

typedef LocalizedArgument = String Function(int index);

extension AppLocalizedContext on BuildContext {
  /// Source-key compatibility for dynamic strings and gradually migrated views.
  String translate(String source, [List<Object?> arguments = const []]) {
    final strings = Localizations.of<FpvStrings>(this, FpvStrings);
    return strings == null
        ? interpolateSource(source, arguments)
        : lookupLocalizedMessage(strings, source, arguments);
  }

  /// Type-safe generated accessor with the former no-delegate fallback intact.
  String localized(String source, String Function(FpvStrings) resolve) {
    final strings = Localizations.of<FpvStrings>(this, FpvStrings);
    return strings == null ? source : resolve(strings);
  }

  /// Typed formatting of positional legacy placeholders, evaluated exactly once.
  String localizedWithArgs(
    String source,
    List<Object?> arguments,
    String Function(FpvStrings, LocalizedArgument) resolve,
  ) {
    final strings = Localizations.of<FpvStrings>(this, FpvStrings);
    if (strings == null) return interpolateSource(source, arguments);
    String value(int index) =>
        index < arguments.length ? '${arguments[index]}' : '{$index}';
    return resolve(strings, value);
  }

  /// Use directly for new features hosted inside the localized app shell.
  FpvStrings get fpvStrings {
    final strings = Localizations.of<FpvStrings>(this, FpvStrings);
    assert(
      strings != null,
      'FpvStrings delegate is missing from the widget tree.',
    );
    return strings!;
  }
}
